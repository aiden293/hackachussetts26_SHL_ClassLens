/** A single scheduled meeting (from the BU catalog `meetings` view). */
export type ScheduleEntry = {
  term: string;
  section: string;
  sectionType: string; // Lecture, Discussion, Lab, …
  instructionType: string; // In-Person, …
  campus: string;
  day: string | null; // e.g. "MWF", "TR"
  start: string | null; // "10:10"
  end: string | null; // "11:00"
  building: string | null;
  room: string | null;
  facility: string | null;
};

export type Course = {
  id: string;
  college: string;
  department: string;
  number: string;
  code: string; // e.g. "CAS CS 111"
  title: string;
  credits: number;
  professor: string;
  /**
   * Id of the teacher account that owns (teaches) this course. Retained for
   * when per-teacher ownership is reintroduced (matched to a Clerk user id).
   * Currently any teacher can manage any CS course in the demo.
   */
  ownerId?: string;
  description: string;
  rating: number; // out of 5
  reviewsCount: number;
  level: string;
  semester: string;
  /** Real meeting schedule from the BU Course Catalog (may be empty). */
  schedule?: ScheduleEntry[];
};

